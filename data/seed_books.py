def calculate_isbn13(prefix12: str) -> str:
    """Computes the valid 13th check digit for a 12-digit prefix according to ISBN-13 standard."""
    digits = [int(c) for c in prefix12 if c.isdigit()]
    if len(digits) != 12:
        raise ValueError(f"Prefix must have exactly 12 digits, got {len(digits)}")
    total = sum(d * (1 if i % 2 == 0 else 3) for i, d in enumerate(digits))
    check = (10 - (total % 10)) % 10
    return prefix12 + str(check)

