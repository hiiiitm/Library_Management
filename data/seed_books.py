def get_seed_books() -> list[dict]:
    """Returns 220 fully validated book records with generated book_id, checksum-valid ISBN-13, and author IDs."""
    books = []
    author_id_map = {}
    author_counter = 1
    
    for idx, item in enumerate(RAW_BOOKS, 1):
        book_id = f"B{idx:04d}"
        prefix = item["isbn_prefix"]
        isbn13 = calculate_isbn13(prefix)
        
        # Format authors with stable author_id
        author_objs = []
        for name in item["authors"]:
            if name not in author_id_map:
                author_id_map[name] = f"A{author_counter:04d}"
                author_counter += 1
            author_objs.append({
                "author_id": author_id_map[name],
                "name": name
            })
            
        book_rec = {
            "book_id": book_id,
            "isbn13": isbn13,
            "title": item["title"],
            "authors": author_objs,
            "genres": item["genres"],
            "publisher": item["publisher"],
            "publication_year": item["publication_year"],
            "language": item["language"],
            "pages": item["pages"],
            "description": item["description"],
            "tags": item["tags"],
            "total_copies": item["total_copies"],
            "available_copies": item["total_copies"], # initialized to total_copies; reduced by active loans during dataset generation
            "shelf_location": item["shelf_location"],
            "avg_rating": 0.0,
            "ratings_count": 0,
            "created_at": f"{min(item['publication_year'], 2024)}-01-15T10:00:00Z"
        }
        books.append(book_rec)
        
    return books, author_id_map

